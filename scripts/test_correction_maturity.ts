// 9. a forming (complete === false) 1H candle changes neither age nor anchors
{
  const candles = unitPath(110);
  const forming = { ...candles.at(-1)!, t: new Date(Date.UTC(2025, 5, 1, 72)).toISOString(), o: 110, h: 110, l: 96, c: 96, complete: false } as Candle;
  assert.deepEqual(computeCorrectionMaturity('USD_JPY', [...candles, forming], 'LONG'), computeCorrectionMaturity('USD_JPY', candles, 'LONG'));
  // and live price never enters the maturity calculation
  const f = structuredBullish();
  const a = analyzeCorrection({ pair: 'EUR_USD', ...f }).candidate!;
  const b = analyzeCorrection({ pair: 'EUR_USD', ...f, livePrice: f.livePrice + 3 }).candidate!;
  assert.deepEqual(a.maturity, b.maturity);
}

// 10. missing anchors => null fields, safely (never fabricated)
{
  const allNull = (m: object) => Object.values(m).every(value => value === null);
  assert.ok(allNull(computeCorrectionMaturity('EUR_USD', fixture(.08, .025, -.035).h1, 'LONG')), 'unbroken trend: start not identifiable in history');
  assert.ok(allNull(computeCorrectionMaturity('EUR_USD', unitPath(110).slice(0, 5), 'LONG')), 'too few candles');
  assert.ok(allNull(computeCorrectionMaturity('EUR_USD', [], 'LONG')), 'no candles');
  assert.ok(allNull(computeCorrectionMaturity('USD_JPY', unitPath(115, [68, 121], [69, 119]), 'LONG')), 'start pivot exceeded by a later completed candle');
  // start found, but the impulse's higher-low sequence runs back to the start of history:
  // age/distance kept, impulse + retracement null.
  const noTurn = computeCorrectionMaturity('USD_JPY', path([[0, 101], [10, 103], [20, 99], [30, 105], [40, 100], [55, 120], [65, 110]]), 'LONG');
  assert.equal(noTurn.correctionAgeBars, 10);
  assert.equal(noTurn.correctionStartPrice, 120);
  assert.equal(noTurn.priorImpulseStartPrice, null);
  assert.equal(noTurn.retracementPercent, null);
  assert.equal(noTurn.correctionDepth, null);
  assert.equal(noTurn.crossedEquilibrium, null);
}

