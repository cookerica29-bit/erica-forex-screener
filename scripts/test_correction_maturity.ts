// 14 / 15. lifecycle stages and validation linkage are unchanged by maturity
{
  const dir = await fs.mkdtemp(path_.join(os.tmpdir(), 'maturity-'));
  const f = structuredBullish();
  const candidate = analyzeCorrection({ pair: 'EUR_USD', ...f }).candidate!;
  const withoutMaturity = (c: CorrectionCandidate) => { const copy = structuredClone(c); delete copy.maturity; return copy; };
  const market = new Map([['EUR_USD', { daily: f.daily, h1: f.h1, m30: f.m30, m5: f.m30 }]]);
  const now = '2026-10-01T12:00:00.000Z';
  const runOnce = async (tag: string, c: CorrectionCandidate) => {
    const lifecycle = new CorrectionLifecycleStore(path_.join(dir, `life-${tag}.json`));
    const validations = new CorrectionValidationStore(path_.join(dir, `val-${tag}.json`));
    const reconciled = await lifecycle.reconcile([c], market, new Set(), now);
    await validations.create({ pair: c.pair, correctionEpisodeId: c.episodeId, scanTimestamp: now, dailyThesis: c.thesisDirection,
      h4Context: String(c.h4Structure), h1CorrectionLeg: c.correctionDirection, h1CorrectionStage: c.stage, locationContext: c.location.primaryLabel });
    const synced = await validations.syncLifecycle([c]);
    return { stage: c.stage, lifecycle: reconciled, validations: synced.map(({ createdAt, updatedAt, ...rest }) => rest) };
  };
  const a = await runOnce('with', structuredClone(candidate));
  const b = await runOnce('without', withoutMaturity(candidate));
  assert.deepEqual(a, b, 'lifecycle + validation linkage identical with or without maturity');
  await fs.rm(dir, { recursive: true, force: true });
}

