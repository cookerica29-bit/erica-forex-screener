// Unit path (USD_JPY, pip 0.01). Swing lows 98 @8, 95 @26 (turn), 100 @46;
// swing highs 103 @16, 105 @36, 120 @61. Bullish impulse 95 -> 120 (25),
// correction starts at the 120 pivot (bar 61 = correction bar 0) and runs to
// `end` at bar 71 (correction bar 10).
const unitPath = (end: number, ...tail: Array<[number, number]>) =>
  path([[0, 104], [8, 98], [16, 103], [26, 95], [36, 105], [46, 100], [61, 120], [71, end], ...tail]);

// 1. bullish Daily thesis + bearish 1H correction
{
  const candles = unitPath(110);
  const m = computeCorrectionMaturity('USD_JPY', candles, 'LONG');
  assert.equal(m.correctionStartTime, candles[61].t);
  assert.equal(m.correctionStartPrice, 120);
  assert.equal(m.correctionEndPrice, 110);
  assert.equal(m.correctionDistancePrice, 10);
  assert.equal(m.correctionDistancePips, 1000);
  assert.equal(m.correctionDistancePercent, 8.333);
  assert.equal(m.priorImpulseStartTime, candles[26].t, 'impulse starts at the turn low, not the last higher low');
  assert.equal(m.priorImpulseEndTime, candles[61].t);
  assert.equal(m.priorImpulseStartPrice, 95);
  assert.equal(m.priorImpulseEndPrice, 120);
  assert.equal(m.priorImpulseDistance, 25);
  assert.equal(m.retracementPercent, 40);
}

// 2. bearish Daily thesis + bullish 1H correction (mirror image)
